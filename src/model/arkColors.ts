const BY_ID = new Map(ARK_COLORS.map((c) => [c.id, c]));

export function colorById(id: number): ArkColor | undefined {
  return BY_ID.get(id);
}

/** Label as the palette itself writes it, e.g. `177 - Skobeloff Coloring`. */
export function colorLabel(id: number): string {
  const color = colorById(id);
  return color ? `${color.id} - ${color.name}` : `${id} - (unknown id)`;
}

/** Matches on id or any part of the name, so "177" and "skob" both work. */
export function searchColors(query: string): ArkColor[] {
  const q = query.trim().toLowerCase();
  if (!q) return ARK_COLORS;
  return ARK_COLORS.filter(
    (c) =>
      String(c.id) === q ||
      String(c.id).startsWith(q) ||
      c.name.toLowerCase().includes(q) ||
      c.hex.toLowerCase().startsWith(q.replace(/^#/, "")),
  );
}

/**
 * ARK gives every creature six colour regions. Which ones a given species
 * actually uses varies, and unused regions are simply ignored by the game.
 */
export const COLOR_REGIONS = [0, 1, 2, 3, 4, 5] as const;
export type ColorRegion = (typeof COLOR_REGIONS)[number];
